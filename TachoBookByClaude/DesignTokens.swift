/// (for example `Labels/Primary` is the `LabelsPrimary` color set).
enum DesignTokens {
    /// Figma `spacing/2`.
    static let spacing2: CGFloat = 8
    /// Figma `radius/xl`.
    static let radiusXL: CGFloat = 20
}
